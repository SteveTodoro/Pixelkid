    c: '#8fdcff', b: '#2f80ed', B: '#1d3f8f', a: '#2ee6d6', i: '#e6f7ff', // blues + cyan + ice
    v: '#b28cf5', V: '#6a3cc9', // purples
    n: '#b0703c', N: '#6b4425', t: '#ecd3a4', T: '#c9a56c', // wood + sand
    s: '#f2c39b', S: '#cf9466', h: '#3b2a1f', H: '#8a5a32', // skin, skin shade, dark hair, brown hair
