/* Pixel icon library: native pixel-art stand-ins for emoji, so every lesson keeps the retro game look.
 * Load after pixel.js. Every icon is 16×16, outlined in near-black and coloured from one shared palette (PAL).
 *
 *   Pixel.has(e)        is there a pixel icon for this emoji?
 *   Pixel.icon(e)       the icon as an SVG string (or null)
 *   Pixel.draw(ctx, e, x, y, size, opts)   draw it on a canvas (returns false if there's no icon, so the caller can fall back)
 *   Pixel.KEEP(e)       emoji that stay as text on purpose: flags, arrows, ticks/crosses, coloured squares
 *
 * Any emoji with an icon is swapped automatically wherever it shows up as page text (buttons, cards, speech bubbles…):
 * a MutationObserver replaces it with <span class="pxi">…svg…</span>, sized 1.15em so it scales with the text around it.
 * Mark an element data-no-icons to opt it out. Emoji without an icon simply stay as emoji.
 *
 * Adding an icon: def('🍎', [16 rows of 16 chars]). Each char is a palette key, '.' is see-through.
 * Helpers: rec (recolour), flip (mirror), rot (turn 90°), over (paint a few pixels over another icon; ' ' = leave alone).
 */
