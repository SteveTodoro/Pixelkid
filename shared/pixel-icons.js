  const rec = (rows, map) => rows.map(r => r.replace(/./g, c => (c in map ? map[c] : c)));
  const flip = rows => rows.map(r => [...r].reverse().join(''));
  const rot = rows => [...rows[0]].map((_, x) => rows.map(r => r[x]).reverse().join('')); // 90° clockwise
  const over = (base, top) => base.map((r, y) => [...r].map((c, x) => { const t = top[y] && top[y][x]; return t && t !== ' ' ? t : c; }).join(''));
  const vflip = rows => rows.slice().reverse();
  const lay = (base, top) => base.map((r, y) => [...r].map((c, x) => { const t = top[y] && top[y][x]; return t && t !== '.' ? t : c; }).join('')); // stack two icons
  const get = e => ICONS[norm(e)];
  Pixel._tools = { def, rec, flip, vflip, rot, over, lay, get };
  Pixel._all = () => Object.entries(ICONS);

  // ---------- rendering ----------
  function toSvg(rows) {
    let rects = '';
    rows.forEach((r, y) => {
      for (let x = 0; x < r.length;) {
        const c = r[x], col = PAL[c];
        let n = 1;
        while (x + n < r.length && r[x + n] === c) n++;
        if (col) rects += `<rect x="${x}" y="${y}" width="${n + 0.03}" height="1.03" fill="${col}"/>`;
        x += n;
      }
    });
    return `<svg viewBox="0 0 16 16" xmlns="http://www.w3.org/2000/svg" shape-rendering="crispEdges" aria-hidden="true">${rects}</svg>`;
  }
  const svgCache = {}, canvasCache = {};
  Pixel.has = e => !!ICONS[norm(e)];
  Pixel.icon = e => { const k = norm(e), rows = ICONS[k]; return rows ? (svgCache[k] || (svgCache[k] = toSvg(rows))) : null; };
