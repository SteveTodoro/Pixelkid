  // Draws like ctx.fillText would draw the emoji: centred on x; y is the baseline ('alphabetic', the default) or the middle.
  Pixel.draw = (ctx, e, x, y, size, { baseline = 'alphabetic', angle = 0, flipX = false } = {}) => {
    const c = canvasOf(e);
    if (!c) return false;
    const s = Math.round(size);
    const cy = baseline === 'middle' ? y : y - size * 0.4;
    ctx.save(); ctx.translate(x, cy); if (angle) ctx.rotate(angle); if (flipX) ctx.scale(-1, 1);
    ctx.imageSmoothingEnabled = false;
    ctx.drawImage(c, -s / 2, -s / 2, s, s);
    ctx.restore();
    return true;
  };

